#define CFG_PORT      8269

// WiFi 连不上时的行为
#define WIFI_RETRY_MS 8000               // 重连间隔
#define WIFI_MAX_TRY  40                 // 连这么久还不成功就重启（0=永不重启）

// ---------------------------------------------------------------------------
// 手机扫码配网（开机自检画面上那个二维码）
//
// 原理：板子自己开一个热点，屏幕上画一张 WIFI: 格式的二维码。手机相机扫一下
// 就直接连上这个热点（不用手输密码），再自动弹出下面的配置网页，选 WiFi、填密码、
// 保存 —— 板子写进 NVS 后重启，以后就照这份新账号连。
//
// 为什么用 WIFI: 格式而不是直接放一个网址：网址二维码要求手机**先手动**连上热点
// 才能打开；WIFI: 格式是一步到位的。这也是各家智能家居设备的通行做法。
// ---------------------------------------------------------------------------
#define PROV_AP_PREFIX  "esp32-launcher-"  // 后面接 MAC 后两字节，如 esp32-launcher-A1B2
#define PROV_AP_PASS    "launcher123"      // 热点密码（WPA2 要求至少 8 位）
#define PROV_HTTP_PORT  80
// 已经连上 WiFi 之后，热点再留这么久，方便你临时扫码改网络；
// 期间只要还有手机连着就不关。从没连上过 WiFi 的话热点一直开着 —— 那是唯一的救急入口。
// 为什么是 2 分钟而不是 30 秒：30 秒实测太紧 —— 开机连上 WiFi 到二维码从屏幕上
// 消失本来就只有 20 秒，再叠上"手机解锁→开相机→扫码→连热点→等页面"这一串，
// 很容易刚打开网页热点就没了。2 分钟够从容走完，代价只是 SSID 在列表里多挂一会儿。
#define PROV_AP_GRACE_MS 120000UL

