#define UDP_PORT      8267               // 广播发现用
#define LINK_TOKEN    "esp32launcher"    // 简单握手口令，防止别人乱发指令
// 桌面配置器（ESP32 Configurator.exe）专用的第二个端口。
// 为什么不在 8266 上顺手做：8266 那条连接是 PC 端常驻服务独占的（单客户端），
